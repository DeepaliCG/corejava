package Encapsulation_Student_Example;

public class Student {
	
	private String name;
	private int age;
	
	// Setter method to set name
	public void setname(String sname)
	{
		name = sname;
	}
	
	//setter to set age
	public void setage(int iage)
	{
		age = iage;
	}
	
	//getter to get name
	public String getname()
	{
		return name;
	}
	
	//getter to get age
	public int getage()
	{
		return age;
	}

}
